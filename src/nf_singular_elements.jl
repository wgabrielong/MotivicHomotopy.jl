# [KR21] Algorithm 1: an F₂-basis of the group E_S of S-singular elements
# modulo squares. The algorithm is due to Alfred Czogała (KR credit him in
# their acknowledgments).
#
# [KR21] P. Koprowski and B. Rothkegel, *The anisotropic part of a quadratic
# form over a number field*, arXiv:2109.04172.

# Accumulate (base, exponent) pairs merging equal bases by ==, for both ideal
# and field-element bases: ideal hashing is not guaranteed consistent with ==,
# so a Dict could silently keep two copies of the same base.
function _push_factor!(bases, exps, P, e)
    for (idx, Q) in enumerate(bases)
        if Q == P
            exps[idx] += e
            return nothing
        end
    end
    push!(bases, P)
    push!(exps, ZZRingElem(e))
    nothing
end

"""
    _kr_algorithm_1(K::AbsSimpleNumField, S::Vector)
        -> Vector{FacElem{AbsSimpleNumFieldElem, AbsSimpleNumField}}

An F₂-basis of ``E_S``, the group of S-singular elements of `K` modulo
squares — the elements with even valuation at every prime outside `S`
([KR21] Algorithm 1, due to **Alfred Czogała**). `S` is the finite part of
the place set: a vector of distinct prime ideals of the maximal order that
must contain every dyadic prime (the infinite places, which [KR21] also put
in S, impose nothing here).

The basis realises the split exact sequence
``0 → U_S → E_S → {}_2C_S → 0``: the returned vector is the S-unit
generators modulo squares (torsion first, as Hecke orders them) followed by
one generator ``λ_b`` per basis class ``b`` of the 2-torsion of the S-class
group. Everything is kept in `FacElem` factored form (memo §7); the ``λ_b``
come from `is_principal_fac_elem`, never evaluated. Callers index columns of
the [KR21] Algorithm 8 matrices by position in this vector.

Correct under GRH: `class_group` and `sunit_group_fac_elem` use Hecke's
`GRH = true` default.
"""
function _kr_algorithm_1(K::AbsSimpleNumField, S::Vector)
    OK = maximal_order(K)
    Sv = [P for P in S]
    isempty(Sv) && error("S must contain every dyadic prime of K")
    all(P -> order(P) === OK && is_prime(P), Sv) ||
        error("S must consist of prime ideals of the maximal order of K")
    for i in eachindex(Sv), j in (i + 1):length(Sv)
        Sv[i] == Sv[j] && error("S contains a repeated prime")
    end
    for (P, _) in prime_decomposition(OK, 2)
        any(Q -> Q == P, Sv) || error("S must contain every dyadic prime of K")
    end

    # Step (1): the 2-torsion subgroup 2C_S of the S-class group
    # C_S = C / <[P] : P in S>, read off the SNF of the quotient.
    C, mC = class_group(OK)
    s_classes = [preimage(mC, P) for P in Sv]
    CS, toCS = quo(C, s_classes)
    CSs, fromSnf = snf(CS)

    # Steps (2)-(3): for each basis class of 2C_S, an ideal representative b
    # and a generator lambda_b. (KR ask for prime representatives; only the
    # S-class of b enters the correctness proof, so the reduced ideal the
    # class-group map returns serves.) [b^2] lies in <[P] : P in S>, so
    # b^2 * prod P^-f is principal; its generator is S-singular because its
    # valuation outside S is 2 ord(b).
    A = free_abelian_group(length(Sv))
    phi = hom(A, C, s_classes)
    lambdas = FacElem{AbsSimpleNumFieldElem, AbsSimpleNumField}[]
    for i in 1:ngens(CSs)
        d = order(CSs[i])
        iseven(d) || continue
        t = fromSnf(divexact(d, 2) * CSs[i])           # order-2 class in C_S
        fl, c = has_preimage_with_preimage(toCS, t)
        fl || error("internal error: cannot lift a class from C_S to C")
        b = mC(c)
        fl2, f = has_preimage_with_preimage(phi, 2 * c)
        fl2 || error("internal error: [b^2] is not in the subgroup generated by S")
        bases = typeof(b)[]
        exps = ZZRingElem[]
        _push_factor!(bases, exps, b, ZZRingElem(2))
        for (j, P) in enumerate(Sv)
            iszero(f[j]) || _push_factor!(bases, exps, P, -f[j])
        end
        fl3, lam = is_principal_fac_elem(FacElem(bases, exps))
        fl3 || error("internal error: b^2 is not principal modulo S")
        push!(lambdas, lam)
    end

    # Step (4): a basis of U_S modulo squares — the S-unit generators in
    # factored form. The torsion generator contributes because the number of
    # roots of unity is even in every number field.
    U, mU = sunit_group_fac_elem(Sv)
    sunits = [mU(U[i]) for i in 1:ngens(U)]

    # Step (5): the sequence 0 -> U_S -> E_S -> 2C_S -> 0 splits, so the
    # union is a basis.
    vcat(sunits, lambdas)
end
